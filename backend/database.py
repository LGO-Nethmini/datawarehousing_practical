from __future__ import annotations

from typing import Any
from datetime import date

import oracledb

from config import DB_CONFIG


class Database:
    def __init__(self):
        try:
            dsn = oracledb.makedsn(
                DB_CONFIG["host"],
                DB_CONFIG["port"],
                service_name=DB_CONFIG["service_name"],
            )
            self.connection = oracledb.connect(
                user=DB_CONFIG["user"],
                password=DB_CONFIG["password"],
                dsn=dsn,
            )
            self.cursor = self.connection.cursor()
            # Set Oracle date format explicitly
            self.cursor.execute("ALTER SESSION SET NLS_DATE_FORMAT='YYYY-MM-DD'")
            self.connection.commit()
        except oracledb.DatabaseError as e:
            raise RuntimeError(f"Database connection failed: {e}")

    def close(self) -> None:
        self.cursor.close()
        self.connection.close()

    def _rows_to_dicts(self, rows: list[tuple[Any, ...]]) -> list[dict[str, Any]]:
        columns = [col[0].lower() for col in self.cursor.description or []]
        return [dict(zip(columns, row)) for row in rows]

    def _safe_drop(self, statement: str) -> None:
        try:
            self.cursor.execute(statement)
        except oracledb.DatabaseError:
            pass

    def init_oltp_schema(self) -> None:
        self._safe_drop("DROP TABLE Sales CASCADE CONSTRAINTS")
        self._safe_drop("DROP TABLE Products CASCADE CONSTRAINTS")
        self._safe_drop("DROP TABLE Customers CASCADE CONSTRAINTS")
        self._safe_drop("DROP TABLE Locations CASCADE CONSTRAINTS")

        self.cursor.execute(
            """
            CREATE TABLE Customers (
                customer_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                first_name VARCHAR2(50) NOT NULL,
                last_name VARCHAR2(50) NOT NULL,
                email VARCHAR2(100),
                phone VARCHAR2(20)
            )
            """
        )

        self.cursor.execute(
            """
            CREATE TABLE Products (
                product_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                product_name VARCHAR2(100) NOT NULL,
                category VARCHAR2(50),
                price NUMBER(10,2)
            )
            """
        )

        self.cursor.execute(
            """
            CREATE TABLE Locations (
                location_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                city VARCHAR2(50),
                state VARCHAR2(50),
                country VARCHAR2(50)
            )
            """
        )

        self.cursor.execute(
            """
            CREATE TABLE Sales (
                sale_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                customer_id NUMBER REFERENCES Customers(customer_id),
                product_id NUMBER REFERENCES Products(product_id),
                location_id NUMBER REFERENCES Locations(location_id),
                sale_date DATE,
                quantity NUMBER,
                total_amount NUMBER(10,2)
            )
            """
        )

        self.connection.commit()

