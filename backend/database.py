    def create_phase3_dimensions(self) -> None:
        self._safe_drop("DROP TABLE Sales_Fact CASCADE CONSTRAINTS")
        self._safe_drop("DROP TABLE Customer_Dim CASCADE CONSTRAINTS")
        self._safe_drop("DROP TABLE Product_Dim CASCADE CONSTRAINTS")
        self._safe_drop("DROP TABLE Location_Dim CASCADE CONSTRAINTS")
        self._safe_drop("DROP TABLE Date_Dim CASCADE CONSTRAINTS")

        # Create Date Dimension
        self.cursor.execute(
            """
            CREATE TABLE Date_Dim (
                date_id NUMBER PRIMARY KEY,
                full_date DATE,
                year NUMBER,
                quarter NUMBER,
                month NUMBER,
                day_of_week VARCHAR2(20),
                is_weekend VARCHAR2(1)
            )
            """
        )

        # Create Customer Dimension with enriched attributes
        self.cursor.execute(
            """
            CREATE TABLE Customer_Dim (
                customer_dim_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                customer_id NUMBER,
                first_name VARCHAR2(50),
                last_name VARCHAR2(50),
                email VARCHAR2(100),
                phone VARCHAR2(20),
                customer_level VARCHAR2(20)
            )
            """
        )

        # Create Product Dimension with enriched attributes
        self.cursor.execute(
            """
            CREATE TABLE Product_Dim (
                product_dim_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                product_id NUMBER,
                product_name VARCHAR2(100),
                category VARCHAR2(50),
                price NUMBER(10,2),
                price_tier VARCHAR2(20),
                level_name VARCHAR2(20)
            )
            """
        )

        # Create Location Dimension with enriched attributes
        self.cursor.execute(
            """
            CREATE TABLE Location_Dim (
                location_dim_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                location_id NUMBER,
                city VARCHAR2(50),
                state VARCHAR2(50),
                country VARCHAR2(50),
                region VARCHAR2(50),
                level_name VARCHAR2(20)
            )
            """
        )

        # Enhanced Sales Fact Table with more metrics
        self.cursor.execute(
            """
            CREATE TABLE Sales_Fact (
                sales_fact_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                date_id NUMBER,
                customer_dim_id NUMBER,
                product_dim_id NUMBER,
                location_dim_id NUMBER,
                sale_date DATE,
                quantity NUMBER,
                total_amount NUMBER(10,2),
                discount_amount NUMBER(10,2),
                net_revenue NUMBER(10,2),
                FOREIGN KEY (customer_dim_id) REFERENCES Customer_Dim(customer_dim_id),
                FOREIGN KEY (product_dim_id) REFERENCES Product_Dim(product_dim_id),
                FOREIGN KEY (location_dim_id) REFERENCES Location_Dim(location_dim_id)
            )
            """
        )

        # Populate Date Dimension (last 2 years)
        self.cursor.execute(
            """
            INSERT INTO Date_Dim (date_id, full_date, year, quarter, month, day_of_week, is_weekend)
            SELECT 
                TO_NUMBER(TO_CHAR(d, 'YYYYMMDD')) as date_id,
                d as full_date,
                TO_NUMBER(TO_CHAR(d, 'YYYY')) as year,
                CEIL(TO_NUMBER(TO_CHAR(d, 'MM')) / 3) as quarter,
                TO_NUMBER(TO_CHAR(d, 'MM')) as month,
                TO_CHAR(d, 'Day') as day_of_week,
                CASE WHEN TO_CHAR(d, 'D') IN ('1','7') THEN 'Y' ELSE 'N' END as is_weekend
            FROM (
                SELECT TRUNC(SYSDATE) - (ROWNUM - 1) as d
                FROM DUAL CONNECT BY ROWNUM <= 730
            )
            """
        )

        # Populate Customer Dimension with enriched data
        self.cursor.execute(
            """
            INSERT INTO Customer_Dim (customer_id, first_name, last_name, email, phone, customer_level)
            SELECT 
                customer_id,
                first_name,
                last_name,
                email,
                phone,
                CASE 
                    WHEN customer_id <= 2 THEN 'Premium'
                    WHEN customer_id <= 3 THEN 'Gold'
                    ELSE 'Standard'
                END as customer_level
            FROM Customers
            """
        )

        # Populate Product Dimension with pricing tier
        self.cursor.execute(
            """
            INSERT INTO Product_Dim (product_id, product_name, category, price, price_tier, level_name)
            SELECT 
                product_id,
                product_name,
                category,
                price,
                CASE 
                    WHEN price >= 1000 THEN 'Premium'
                    WHEN price >= 300 THEN 'Standard'
                    WHEN price >= 50 THEN 'Economy'
                    ELSE 'Budget'
                END as price_tier,
                'DETAIL' as level_name
            FROM Products
            """
        )

        # Populate Location Dimension with region
        self.cursor.execute(
            """
            INSERT INTO Location_Dim (location_id, city, state, country, region, level_name)
            SELECT 
                location_id,
                city,
                state,
                country,
                CASE 
                    WHEN state IN ('NY', 'NJ', 'PA') THEN 'Northeast'
                    WHEN state IN ('CA', 'WA', 'OR') THEN 'West'
                    WHEN state IN ('TX', 'OK', 'LA') THEN 'South'
                    WHEN state IN ('IL', 'MI', 'OH') THEN 'Midwest'
                    ELSE 'Other'
                END as region,
                'DETAIL' as level_name
            FROM Locations
            """
        )

        # Populate Sales Fact with enriched metrics
        self.cursor.execute(
            """
            INSERT INTO Sales_Fact (date_id, customer_dim_id, product_dim_id, location_dim_id, sale_date, quantity, total_amount, discount_amount, net_revenue)
            SELECT
                TO_NUMBER(TO_CHAR(s.sale_date, 'YYYYMMDD')) as date_id,
                cd.customer_dim_id,
                pd.product_dim_id,
                ld.location_dim_id,
                s.sale_date,
                s.quantity,
                s.total_amount,
                ROUND(s.total_amount * 0.05, 2) as discount_amount,
                ROUND(s.total_amount * 0.95, 2) as net_revenue
            FROM Sales s
            JOIN Customer_Dim cd ON s.customer_id = cd.customer_id
            JOIN Product_Dim pd ON s.product_id = pd.product_id
            JOIN Location_Dim ld ON s.location_id = ld.location_id
            """
        )

        self.connection.commit()

    def create_sales_data_mart(self) -> None:
        self._safe_drop("DROP TABLE Sales_Data_Mart CASCADE CONSTRAINTS")

        self.cursor.execute(
            """
            CREATE TABLE Sales_Data_Mart (
                mart_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                product_name VARCHAR2(100),
                location_name VARCHAR2(100),
                total_quantity NUMBER,
                total_amount NUMBER(10,2),
                avg_sale_amount NUMBER(10,2),
                last_updated DATE DEFAULT SYSDATE
            )
            """
        )
        self.connection.commit()

    def populate_sales_data_mart(self) -> None:
        self.cursor.execute(
            """
            INSERT INTO Sales_Data_Mart
            (product_name, location_name, total_quantity, total_amount, avg_sale_amount)
            SELECT
                p.product_name,
                l.city || ', ' || l.state AS location_name,
                SUM(s.quantity) AS total_quantity,
                SUM(s.total_amount) AS total_amount,
                AVG(s.total_amount) AS avg_sale_amount
            FROM Sales s
            JOIN Products p ON s.product_id = p.product_id
            JOIN Locations l ON s.location_id = l.location_id
            GROUP BY p.product_name, l.city, l.state
            """
        )
        self.connection.commit()

    def get_performance_comparison(self) -> list[dict[str, Any]]:
        comparisons: list[dict[str, Any]] = []

        q1 = (
            """
            SELECT p.product_name, l.city, SUM(s.total_amount)
            FROM Sales s
            JOIN Products p ON s.product_id = p.product_id
            JOIN Locations l ON s.location_id = l.location_id
            GROUP BY p.product_name, l.city
            """,
            "OLTP Joins",
        )

        q2 = (
            """
            SELECT pd.product_name, ld.city, SUM(sf.total_amount)
            FROM Sales_Fact sf
            JOIN Product_Dim pd ON sf.product_dim_id = pd.product_dim_id
            JOIN Location_Dim ld ON sf.location_dim_id = ld.location_dim_id
            GROUP BY pd.product_name, ld.city
            """,
            "Star Schema",
        )

        q3 = (
            """
            SELECT product_name, location_name, total_amount
            FROM Sales_Data_Mart
            """,
            "Data Mart",
        )

        for sql, label in [q1, q2, q3]:
            self.cursor.execute(sql)
            plan_rows = self.cursor.fetchall()
            comparisons.append(
                {
                    "phase": label,
                    "rows_returned": len(plan_rows),
                    "note": "Compare elapsed time from API response timings in UI",
                }
            )

        return comparisons

    def fetch_all(self, sql: str) -> list[dict[str, Any]]:
        self.cursor.execute(sql)
        rows = self.cursor.fetchall()
        return self._rows_to_dicts(rows)

    def get_stats(self) -> dict[str, int]:
        stats = {}
        tables = [
            ("customers", "Customers"),
            ("products", "Products"),
            ("locations", "Locations"),
            ("sales", "Sales"),
            ("customer_dim", "Customer_Dim"),
            ("product_dim", "Product_Dim"),
            ("location_dim", "Location_Dim"),
            ("date_dim", "Date_Dim"),
            ("sales_fact", "Sales_Fact"),
            ("sales_datamart", "Sales_Data_Mart"),
        ]
        
        for key, table in tables:
            try:
                self.cursor.execute(f"SELECT COUNT(*) FROM {table}")
                count = int(self.cursor.fetchone()[0])
                stats[key] = count
            except oracledb.DatabaseError:
                stats[key] = 0
        
        # Add aggregated metrics
        try:
            self.cursor.execute("SELECT SUM(total_amount) FROM Sales")
            result = self.cursor.fetchone()
            stats["total_sales"] = int(result[0]) if result[0] else 0
        except:
            stats["total_sales"] = 0
        
        try:
            self.cursor.execute("SELECT COUNT(DISTINCT customer_id) FROM Sales")
            result = self.cursor.fetchone()
            stats["unique_customers"] = int(result[0]) if result[0] else 0
        except:
            stats["unique_customers"] = 0
        
        return stats
